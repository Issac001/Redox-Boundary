def pooled(out):
    name='figure2_1_pooled';fig=canvas(name);obs=read(OBSERVATIONS)
    p=NUM/'pooled_fit_parameters.json'
    rec=json.loads(p.read_text());INPUTS[path_label(p)]=hashlib.sha256(p.read_bytes()).hexdigest()
    a,A,c,w=[rec['parameters'][x] for x in ['a','A','c','w']]
    ax=panel(fig,[.10,.13,.875,.68])
    for case,color in zip(CASES,[COLORS[1],COLORS[2],COLORS[0]]):
        g=obs[obs.Case==case];ax.scatter(g.Depth,g.Eh,s=4,alpha=.35,edgecolors='none',color=color,label=f'Case {case}: {g.profile_id.nunique()} profiles')
    curve=read(NUM/'pooled_sigmoid_predictions.csv');ax.plot(curve.depth_cm,curve.Eh_mV,color='black',lw=1.1)
    pred=a+A/(1+np.exp((obs.Depth.to_numpy()-c)/w));rmse=float(np.sqrt(np.mean((obs.Eh-pred)**2)));r2=float(1-np.sum((obs.Eh-pred)**2)/np.sum((obs.Eh-obs.Eh.mean())**2))
    assert abs(rmse-rec['rmse'])<1e-5 and abs(r2-rec['r2'])<1e-7
    ax.text(.05,.075,f'Pooled sigmoid fit\nRMSE = {rmse:.1f} mV\n$R^2$ = {r2:.1f}',transform=ax.transAxes,fontsize=8.5,linespacing=1.5)
    ax.set(xlim=(8,97),ylim=(-520,760),xticks=[10,20,30,40,50,60,70,80,90,95],yticks=[-400,-200,0,200,400,600],xlabel='Depth below column top (cm)',ylabel='Eh (mV)')
    fig.suptitle('Pooled Eh profiles and sigmoid fit',y=.97,fontsize=10)
    handles=[Line2D([],[],ls='',marker='o',color=col,ms=3,label=f'Case {case}: {obs[obs.Case==case].profile_id.nunique()} profiles') for case,col in zip(CASES,[COLORS[1],COLORS[2],COLORS[0]])]
    fig.legend(handles=handles,loc='upper center',bbox_to_anchor=(.54,.918),ncol=3,frameon=False,columnspacing=1,fontsize=7.5)
    finish(fig,name,out);AUDIT[name]['pooled_fit']={'parameters':rec['parameters'],'rmse':rmse,'r2':r2}

FUNCTIONS={'figure2_1_pooled':pooled,'figure1_profiles_and_centers':figure1,'figure2_eh_maps':figure2,'figure3_lodo_comparison':figure3,
           'figure4_simulation_comparison':figure4,'figure5_chemical_centers':figure5,'figureC1_threshold_diagnostic':figureC1}
def _render(results_dir, observation_path, output_dir, font_family, selected):
    global RESULTS, NUM, RAW, OBSERVATIONS, FONT_FAMILY
    RESULTS=Path(results_dir).resolve()
    NUM=RESULTS/'numeric'
    RAW=RESULTS/'raw'
    OBSERVATIONS=Path(observation_path).resolve()
    FONT_FAMILY=font_family
    out=Path(output_dir).resolve() if output_dir is not None else RESULTS/'figures'
    INPUTS.clear()
    AUDIT.clear()
    with plt.rc_context():
        style(font_family)
        out.mkdir(parents=True,exist_ok=True)
        for name in selected:
            FUNCTIONS[name](out)
            print(name,flush=True)
    audit={'source':str(Path(__file__).relative_to(ROOT)),
           'inputs_sha256':dict(INPUTS),'figures':dict(AUDIT)}
    audit_path=out/'figure_style_audit.json'
    audit_path.write_text(json.dumps(audit,ensure_ascii=False,indent=2))
    return audit


def render_all(results_dir, observation_path, output_dir=None,
               font_family='Times New Roman'):
    """Render all seven figures from numeric/ and raw/ under results_dir.

    Input and output locations can be outside the source checkout. The default
    manuscript font must be installed; alternatives require explicit selection.
    """
    return _render(results_dir,observation_path,output_dir,font_family,list(FUNCTIONS))


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results',type=Path,default=ROOT/'results_manuscript')
    parser.add_argument('--observations',type=Path,
                        default=ROOT/'data/manuscript/eh_observations.csv')
    parser.add_argument('--out',type=Path)
    parser.add_argument('--figure',choices=FUNCTIONS)
