def canvas(name):
    w,h=CANVASES[name]
    return plt.figure(figsize=(w/300,h/300),dpi=300)

def panel(fig,bounds,*,square=False,xnumeric=True,ynumeric=True):
    ax=fig.add_axes(bounds)
    if square:ax.set_box_aspect(1)
    ax._paper_square=square
    ax._paper_numeric=(xnumeric,ynumeric)
    return ax

def numeric_signature(fig):
    h=hashlib.sha256()
    for ax in fig.axes:
        arrays=[ax.get_xlim(),ax.get_ylim()]
        for line in ax.lines:arrays.extend([line.get_xdata(),line.get_ydata()])
        for coll in ax.collections:
            arrays.extend([coll.get_offsets(),coll.get_array()])
        for patch in ax.patches:arrays.append(patch.get_path().vertices)
        for values in arrays:
            if values is None:continue
            x=np.ma.asarray(values,dtype=float);h.update(str(x.shape).encode());h.update(np.ma.filled(x,np.nan).tobytes())
    return h.hexdigest()

def finish(fig,name,out):
    """One style hook for every figure, including ticks, legends, and colorbars."""
    before=numeric_signature(fig)
    for ax in fig.axes:
        ax.grid(False,which='both',axis='both')
        ax.set_facecolor('white')
        for sp in ax.spines.values():sp.set_visible(True);sp.set_color('black');sp.set_linewidth(.7)
        ax.tick_params(colors='black',direction='out',top=False,right=False)
        xn,yn=getattr(ax,'_paper_numeric',(False,True))
        if xn:ax.xaxis.set_major_formatter(FormatStrFormatter('%.1f'))
        if yn:ax.yaxis.set_major_formatter(FormatStrFormatter('%.1f'))
    fig.canvas.draw()
    for artist in fig.findobj(match=Text):
        artist.set_color('black');artist.set_fontfamily(FONT_FAMILY)
    fig.canvas.draw()
    assert before==numeric_signature(fig),f'Presentation changed plotted numerical values: {name}'
    checks=[]
    for ax in fig.axes:
        if getattr(ax,'_paper_square',False):
            box=ax.get_window_extent();ratio=box.width/box.height
            assert abs(ratio-1)<1e-6,(name,ratio)
            checks.append({'box_width_height_ratio':ratio,'all_four_spines':all(ax.spines[e].get_visible() for e in ['left','right','top','bottom'])})
        assert not any(x.get_visible() for x in ax.get_xgridlines()+ax.get_ygridlines())
    assert all(mcolors.to_rgba(t.get_color())[:3]==(0,0,0) for t in fig.findobj(match=Text))
    outputs=[]
    for ext in ['png','pdf','svg']:
        p=out/f'{name}.{ext}';fig.savefig(p,dpi=300);outputs.append(path_label(p))
    AUDIT[name]={'numerical_signature_unchanged':before,'square_panels':checks,'text_color':'black',
                 'font':FONT_FAMILY,'numeric_tick_decimals':1,'background_grid':False,'outputs':outputs}
    plt.close(fig)

def method_legend(fig,y=.99):
    fig.legend(handles=[Line2D([],[],ls='',marker=m,color=c,ms=5,label=l)
                        for m,c,l in zip(MARKERS,COLORS,METHOD_LABELS)],
               loc='upper center',bbox_to_anchor=(.54,y),ncol=3,frameon=False,columnspacing=1.7)

def edges(values):
    a=np.asarray(values);return np.r_[a[0],(a[1:]+a[:-1])/2,a[-1]]

